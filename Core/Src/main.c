/**
  * @brief System Clock Configuration
  * @retval None
  */
void SystemClock_Config(void)
{
  RCC_OscInitTypeDef RCC_OscInitStruct = {0};
  RCC_ClkInitTypeDef RCC_ClkInitStruct = {0};

  /** Configure the main internal regulator output voltage
  *  (Range 1 is required for 160 MHz; HAL also enables the EPOD booster)
  */
  if (HAL_PWREx_ControlVoltageScaling(PWR_REGULATOR_VOLTAGE_SCALE1) != HAL_OK)
  {
    Error_Handler();
  }

  /* HSE 16 MHz crystal (PH0/PH1) -> PLL1: M=1, N=20 -> VCO 320 MHz
   * R=2 -> 160 MHz SYSCLK, Q=4 -> 80 MHz (FDCAN kernel), P=4 -> 80 MHz */
  RCC_OscInitStruct.OscillatorType = RCC_OSCILLATORTYPE_HSE;
  RCC_OscInitStruct.HSEState = RCC_HSE_ON;
  RCC_OscInitStruct.PLL.PLLState = RCC_PLL_ON;
  RCC_OscInitStruct.PLL.PLLSource = RCC_PLLSOURCE_HSE;
  RCC_OscInitStruct.PLL.PLLMBOOST = RCC_PLLMBOOST_DIV1;
  RCC_OscInitStruct.PLL.PLLM = 1;
  RCC_OscInitStruct.PLL.PLLN = 20;
  RCC_OscInitStruct.PLL.PLLP = 4;
  RCC_OscInitStruct.PLL.PLLQ = 4;
  RCC_OscInitStruct.PLL.PLLR = 2;
  RCC_OscInitStruct.PLL.PLLRGE = RCC_PLLVCIRANGE_1;
  RCC_OscInitStruct.PLL.PLLFRACN = 0;
  if (HAL_RCC_OscConfig(&RCC_OscInitStruct) != HAL_OK)
  {
    /* HSE did not start: fall back to the previously verified HSI 120 MHz */
    RCC_OscInitTypeDef fb = {0};
    fb.OscillatorType = RCC_OSCILLATORTYPE_HSI;
    fb.HSIState = RCC_HSI_ON;
    fb.HSICalibrationValue = RCC_HSICALIBRATION_DEFAULT;
    fb.PLL.PLLState = RCC_PLL_ON;
    fb.PLL.PLLSource = RCC_PLLSOURCE_HSI;
    fb.PLL.PLLMBOOST = RCC_PLLMBOOST_DIV1;
    fb.PLL.PLLM = 1;
    fb.PLL.PLLN = 15;
    fb.PLL.PLLP = 3;
    fb.PLL.PLLQ = 3;
    fb.PLL.PLLR = 2;
    fb.PLL.PLLRGE = RCC_PLLVCIRANGE_1;
    fb.PLL.PLLFRACN = 0;
    if (HAL_RCC_OscConfig(&fb) != HAL_OK)
    {
      Error_Handler();
    }
  }

  /* Step 1: switch SYSCLK to PLL with HCLK = SYSCLK/2 (80 MHz) to limit the
   * current step on VCAP, as recommended by RM0456 for HCLK > 55 MHz. */
  RCC_ClkInitStruct.ClockType = RCC_CLOCKTYPE_HCLK|RCC_CLOCKTYPE_SYSCLK
                              |RCC_CLOCKTYPE_PCLK1|RCC_CLOCKTYPE_PCLK2
                              |RCC_CLOCKTYPE_PCLK3;
  RCC_ClkInitStruct.SYSCLKSource = RCC_SYSCLKSOURCE_PLLCLK;
  RCC_ClkInitStruct.AHBCLKDivider = RCC_SYSCLK_DIV2;
  RCC_ClkInitStruct.APB1CLKDivider = RCC_HCLK_DIV1;
  RCC_ClkInitStruct.APB2CLKDivider = RCC_HCLK_DIV1;
  RCC_ClkInitStruct.APB3CLKDivider = RCC_HCLK_DIV1;
  if (HAL_RCC_ClockConfig(&RCC_ClkInitStruct, FLASH_LATENCY_4) != HAL_OK)
  {
    Error_Handler();
  }

  /* Short settling delay (>1 us; ~80 MHz core), then Step 2: HCLK = SYSCLK */
  for (volatile uint32_t i = 0; i < 2000U; i++) { __NOP(); }

  RCC_ClkInitStruct.AHBCLKDivider = RCC_SYSCLK_DIV1;
  if (HAL_RCC_ClockConfig(&RCC_ClkInitStruct, FLASH_LATENCY_4) != HAL_OK)
  {
    Error_Handler();
  }
}

